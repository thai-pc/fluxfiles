async function openUi(page, extraClaims = {}) {
  const tok = tokenFor(UI_USER, extraClaims);
  await page.goto(`${BASE}/public/index.html?token=${tok}&disk=local`);
  await page.locator('.ff-app').waitFor({ state: 'visible', timeout: 15000 });
  await page.waitForLoadState('networkidle');
}
async function enter(page, folder) {
  await card(page, folder).dblclick();
  await page.locator('.ff-breadcrumb, .breadcrumb').getByText(folder, { exact: true }).first()
    .waitFor({ timeout: 10000 }).catch(() => {});
  await page.waitForLoadState('networkidle');
  await page.waitForTimeout(300);
}
async function contextMenu(page, name, item) {
  await card(page, name).click({ button: 'right' });
  const menu = page.locator('.ff-context-menu');
  await menu.waitFor({ state: 'visible' });
  await menu.getByText(item, { exact: true }).click();
}
async function settle(page) {
  await page.mouse.move(2, 818);
  await page.waitForLoadState('networkidle');
  await page.waitForTimeout(600); // x-transition + blur
}
async function assertClean(page, dialog) {
  const toastErr = page.locator('.ff-toast.ff-toast-error');
  if (await toastErr.isVisible().catch(() => false)) throw new Error('error toast visible: ' + await toastErr.innerText());
  if (dialog) {
    const errs = dialog.locator('.ff-new-folder-error:visible');
    if (await errs.count()) throw new Error('error in dialog: ' + await errs.first().innerText());
  }
}

