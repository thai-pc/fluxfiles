// ── main ─────────────────────────────────────────────────────────────────────
const results = [];
try {
  await waitForServer();
  log(`server up on ${BASE} (core copy: ${core})`);
  await seed();
  log('demo content seeded');

  mkdirSync(outDir, { recursive: true });
  const browser = await chromium.launch();
  for (const [id, shot] of Object.entries(SHOTS)) {
    if (ONLY && !ONLY.has(id)) continue;
    const file = `fluxfiles-demo-${id}.png`;
    const missing = (shot.needs || []).filter((b) => !engines[b]);
    if (missing.length) { results.push([file, `skipped — missing ${missing.join(', ')}`]); continue; }
    if (shot.paid && !(licensed && shot.paid.every((m) => installed.includes(m)))) {
      results.push([file, 'skipped — paid module not installed/licensed here']); continue;
    }
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 820 }, deviceScaleFactor: 1,
      locale: 'en-US', colorScheme: 'light' });
    await ctx.addInitScript(() => { try { localStorage.setItem('fluxfiles_theme', 'light'); } catch { /* opaque origin */ } });
    const page = await ctx.newPage();
    try {
      const dialog = await shot.run(page);
      await settle(page);
      await assertClean(page, dialog);
      await page.screenshot({ path: join(outDir, file) });
      results.push([file, 'ok']);
      if (COPY_TO) copyFileSync(join(outDir, file), join(COPY_TO, file));
    } catch (e) {
      await page.screenshot({ path: join(outDir, `FAILED-${file}`) }).catch(() => {});
      results.push([file, `FAILED — ${e.message.split('\n')[0]}`]);
    } finally {
      await ctx.close();
    }
  }
  await browser.close();
} finally {
  cleanup();
}

console.log(`\nvirus engine: ${virusEngine === 'stub' ? 'demo clamdscan stand-in (no ClamAV on this machine)' : 'ClamAV'}`);
for (const [f, s] of results) console.log(`${s === 'ok' ? '✔' : '✘'} ${f}  ${s}`);
console.log(`\noutput: ${outDir}${COPY_TO ? `\ncopied to: ${COPY_TO}` : ''}`);
process.exitCode = results.some(([, s]) => s.startsWith('FAILED')) ? 1 : 0;
