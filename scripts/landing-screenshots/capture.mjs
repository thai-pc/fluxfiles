async function waitForServer() {
  for (let i = 0; i < 100; i++) {
    try { if ((await fetch(`${BASE}/public/`)).ok) return; } catch { /* not up yet */ }
    await new Promise((r) => setTimeout(r, 150));
  }
  throw new Error(`server did not start on ${BASE}\n${serverErr}`);
}

// ── 4. API helpers ───────────────────────────────────────────────────────────
function mint(claims) {
  return execFileSync('php', [join(here, 'lib', 'mint.php'), JSON.stringify(claims)],
    { env: { ...process.env, FF_SHOT_SECRET: SECRET } }).toString().trim();
}
const BASE_CLAIMS = { perms: ['read', 'write', 'delete', 'audit'], disks: ['local'], prefix: '', max_upload: 10 };
const tokenFor = (sub, extra = {}) => mint({ ...BASE_CLAIMS, sub, ...extra });

async function api(token, method, path, body) {
  const res = await fetch(BASE + path, {
    method,
    headers: { Authorization: `Bearer ${token}`, ...(body ? { 'Content-Type': 'application/json' } : {}) },
    body: body ? JSON.stringify(body) : undefined,
  });
  const j = await res.json().catch(() => ({}));
  if (!res.ok || j.error) throw new Error(`${method} ${path} → ${res.status} ${j.error_code || ''} ${j.error || ''}`);
  return j.data;
}
async function upload(token, key, bytes, mime) {
  const fd = new FormData();
  const dir = key.includes('/') ? key.slice(0, key.lastIndexOf('/')) : '';
  fd.set('disk', 'local');
  fd.set('path', dir);
  fd.set('file', new Blob([bytes], { type: mime }), key.slice(key.lastIndexOf('/') + 1));
  const res = await fetch(`${BASE}/api/fm/upload`, { method: 'POST', headers: { Authorization: `Bearer ${token}` }, body: fd });
  const j = await res.json().catch(() => ({}));
  if (!res.ok || j.error) throw new Error(`upload ${key} → ${res.status} ${j.error_code || ''} ${j.error || ''}`);
  return j.data;
}

