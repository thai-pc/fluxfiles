/** An abstract "landscape" photo: sky gradient over ground gradient, soft horizon, optional sun. */
function photo(name, [sky1, sky2, ground1, ground2], sun = null) {
  const out = join(assets, name);
  magick('-size', '1200x470', `gradient:${sky1}-${sky2}`, '-size', '1200x330', `gradient:${ground1}-${ground2}`, '-append',
    ...(sun ? ['-fill', sun, '-draw', 'circle 820,330 820,262'] : []),
    '-blur', '0x7', '-quality', '86', out);
  return read(out);
}

/**
 * A one-page document PDF. `cover` → a full-bleed colour cover with a centred
 * title (reads well as a grid poster); otherwise a letter-style page with a
 * header band and body "text" bars.
 */
function docPdf(name, title, subtitle, accent, { lines = 14, footer = '', cover = false } = {}) {
  const png = join(assets, name.replace(/\.pdf$/, '') + '.png');
  if (cover) {
    magick('-size', '1240x1754', `gradient:${accent}-#111827`,
      '-font', FONT_BOLD, '-fill', 'white', '-pointsize', '104', '-gravity', 'center', '-annotate', '+0-60', title,
      '-font', FONT, '-pointsize', '44', '-annotate', '+0+60', subtitle,
      '-pointsize', '26', '-gravity', 'south', '-annotate', '+0+90', footer || 'Northwind Studio',
      png);
  } else {
    const draw = [];
    for (let i = 0; i < lines; i++) {
      const y = 620 + i * 58;
      const w = 760 + ((i * 137) % 220) - (i % 5 === 4 ? 360 : 0);
      draw.push('-draw', `rectangle 120,${y} ${120 + w},${y + 16}`);
    }
    magick('-size', '1240x1754', 'xc:white',
      '-fill', accent, '-draw', 'rectangle 0,0 1240,430',
      '-font', FONT_BOLD, '-fill', 'white', '-pointsize', '64', '-annotate', '+120+250', title,
      '-font', FONT, '-pointsize', '32', '-annotate', '+120+320', subtitle,
      '-fill', '#e5e7eb', ...draw,
      '-fill', '#9ca3af', '-pointsize', '22', '-annotate', '+120+1680', footer || 'Northwind Studio · Confidential',
      png);
  }
  const out = join(assets, name);
  magick(png, '-units', 'PixelsPerInch', '-density', '150', '-quality', '82', '-compress', 'jpeg', out);
  return read(out);
}

/** A short title-card clip (slow push-in) — needs ffmpeg. */
function clip(name, title, subtitle, c1, c2) {
  const card = join(assets, name.replace(/\.mp4$/, '') + '.png');
  magick('-size', '1280x720', `gradient:${c1}-${c2}`,
    '-font', FONT_BOLD, '-fill', 'white', '-pointsize', '68', '-gravity', 'center', '-annotate', '+0-30', title,
    '-font', FONT, '-pointsize', '30', '-annotate', '+0+50', subtitle, card);
  const out = join(assets, name);
  execFileSync(engines.ffmpeg, ['-y', '-loglevel', 'error', '-i', card, '-vf',
    "zoompan=z='min(zoom+0.0015,1.12)':d=75:s=1280x720:fps=25,format=yuv420p",
    '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '30', '-movflags', '+faststart', out]);
  return read(out);
}

